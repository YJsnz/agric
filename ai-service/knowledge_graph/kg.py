"""Evidence-aware graph tooling. Python 3.10+, standard library only."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def read(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def validate(graph, ontology):
    def require(ok, message):
        if not ok:
            raise ValueError(message)

    nodes = {n["id"]: n for n in graph["nodes"]}
    sources = {s["id"]: s for s in graph["sources"]}
    require(len(nodes) == len(graph["nodes"]), "duplicate node id")
    require(len(sources) == len(graph["sources"]), "duplicate source id")
    require(not nodes.keys() & sources.keys(), "node/source id collision")
    for n in nodes.values():
        require(n["type"] in ontology["node_types"], "unknown node type")
        require(bool(n["name"]), "empty node name")
    seen, adjacency = set(), {key: [] for key in nodes}
    for e in graph["edges"]:
        require(e["id"] not in seen, "duplicate edge id")
        seen.add(e["id"])
        require(e["source"] in nodes and e["target"] in nodes, "dangling endpoint")
        require(e["relation"] in ontology["relations"], "unknown relation")
        r = ontology["relations"][e["relation"]]
        require(e["kind"] == r["kind"], "relation kind mismatch")
        require(nodes[e["source"]]["type"] in r["domain"], "invalid domain")
        require(nodes[e["target"]]["type"] in r["range"], "invalid range")
        require(e["scope"] in ontology["scopes"], "invalid scope")
        require(e["review_status"] in ontology["review_statuses"], "invalid review status")
        require(bool(e["evidence_ids"]) and all(s in sources for s in e["evidence_ids"]), "missing evidence")
        require(bool(e["claim"]) and bool(e["locator"]), "missing claim/locator")
        require(e["crop"] in nodes and nodes[e["crop"]]["type"] == "Crop", "invalid crop")
        require(all(s in nodes and nodes[s]["type"] == "Stage" for s in e["stage_ids"]), "invalid stage")
        require(e["confidence"] is None and e["effect_size"] is None, "V1 has no calibrated probabilities")
        if e["kind"] == "hypothesis":
            require(e["review_status"] == "draft", "hypothesis cannot be verified")
        if e["kind"] == "mechanism":
            require(all(sources[s]["status"] == "read" for s in e["evidence_ids"]), "mechanism needs read evidence")
            require(bool(e["conditions"]), "mechanism needs conditions")
        if e["scope"] == "general_pear":
            require(e["review_status"] == "transfer_pending", "general evidence requires local review")
        if e["kind"] in ontology["causal_kinds"]:
            adjacency[e["source"]].append(e["target"])
    active, done = set(), set()

    def visit(node):
        require(node not in active, "causal cycle")
        if node in done:
            return
        active.add(node)
        for target in adjacency[node]:
            visit(target)
        active.remove(node)
        done.add(node)
    for node in nodes:
        visit(node)
    return {"nodes": len(nodes), "edges": len(seen), "sources": len(sources)}


def literal(value):
    if value is None:
        return "null"
    if isinstance(value, list):
        return "[" + ", ".join(literal(v) for v in value) + "]"
    return json.dumps(value, ensure_ascii=False)


def properties(data):
    for key in data:
        if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", key):
            raise ValueError("invalid property key")
    return "{" + ", ".join(k + ": " + literal(v) for k, v in data.items()) + "}"


def export(graph, directory):
    directory.mkdir(parents=True, exist_ok=True)
    lines = ["// Generated by kg.py; scoped to KGEntity. No APOC, no deletes.",
             "CREATE CONSTRAINT kg_entity_id IF NOT EXISTS FOR (n:KGEntity) REQUIRE n.id IS UNIQUE;"]
    for n in graph["nodes"] + [dict(s, type="Source") for s in graph["sources"]]:
        label = n["type"]
        if not re.fullmatch(r"[A-Za-z][A-Za-z_0-9]*", label):
            raise ValueError("invalid label")
        lines.append(f'MERGE (n:KGEntity {{id: {literal(n["id"])}}}) SET n:{label}, n += {properties(n)};')
    for e in graph["edges"]:
        props = {k: v for k, v in e.items() if k not in ("source", "target", "relation")}
        lines.append(f'MATCH (a:KGEntity {{id: {literal(e["source"])}}}), (b:KGEntity {{id: {literal(e["target"])}}}) MERGE (a)-[r:{e["relation"]} {{id: {literal(e["id"])}}}]->(b) SET r += {properties(props)};')
    (directory / "import.cypher").write_text("\n".join(lines) + "\n", encoding="utf-8")
    diagram = ["# 泊头鸭梨知识图谱 V1", "", "虚线为待验证假设；流程边不表示因果。", "", "```mermaid", "flowchart LR"]
    identifiers = {n["id"]: f"n{i}" for i, n in enumerate(graph["nodes"])}
    for n in graph["nodes"]:
        diagram.append(f'  {identifiers[n["id"]]}["{n["name"]}"]')
    for e in graph["edges"]:
        arrow = "-.->" if e["kind"] == "hypothesis" else "-->"
        diagram.append(f'  {identifiers[e["source"]]} {arrow}|{e["relation"]}| {identifiers[e["target"]]}')
    diagram.append("```")
    (directory / "graph.md").write_text("\n".join(diagram) + "\n", encoding="utf-8")


def neighborhood(graph, node, mode):
    if node not in {n["id"] for n in graph["nodes"]}:
        raise ValueError("unknown node")
    edges = [e for e in graph["edges"] if node in (e["source"], e["target"])]
    if mode == "local":
        edges = [e for e in edges if e["scope"] == "local" and e["review_status"] in ("source_checked", "local_expert_reviewed") and e["kind"] == "fact"]
    return {"mode": mode, "edges": edges, "notice": "仅查询知识关系；不作诊断或定量反事实推断。无本地证据时返回空结果。"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["validate", "export", "query"])
    parser.add_argument("--data", type=Path, default=ROOT / "data/graph.json")
    parser.add_argument("--output", type=Path, default=ROOT / "generated")
    parser.add_argument("--node", default="disease:scab")
    parser.add_argument("--mode", choices=["local", "research"], default="local")
    args = parser.parse_args()
    graph = read(args.data)
    result = validate(graph, read(ROOT / "ontology.json"))
    if args.command == "export":
        export(graph, args.output)
        result["output"] = str(args.output)
    elif args.command == "query":
        result = neighborhood(graph, args.node, args.mode)
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
